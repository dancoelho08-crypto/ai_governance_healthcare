@router.get("/projects/{project_id}/versions", tags=["versions"])
async def list_versions(
    request: Request,
    project_id: str = ProjectId,
    db: Database = Depends(get_db),
    settings: Settings = Depends(get_settings),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
) -> list[dict[str, Any]]:
    """Every recorded revision of this project, newest first.

    Metadata only -- revision, fingerprint, who, when. The documents
    themselves are fetched one at a time, because returning fifty full
    snapshots to render a list is a lot of bytes for a column of dates.

    Access is checked against the live project, or -- when it has been deleted
    -- against the access list recorded on its most recent snapshot. A deleted
    project keeps its versions on purpose (see 002_versions.sql), and it must
    not become readable to everyone in the process: "it was deleted, and here
    is what it said" is the audit answer for the people who could read it, not
    for everybody with an account.
    """
    async with db.acquire() as conn, conn.transaction():
        gate = await _version_gate(conn, project_id)
        if gate is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "No such project")
        doc, incarnation = gate
        if require(
            doc,
            identity.id,
            Level.READ,
            enforced=settings.require_identity,
            project_id=project_id,
            emergency=identity.emergency,
        ):
            await emergency.record(
                conn, identity, project_id, "read this project's history", Use.READ
            )
        await record_access(
            conn,
            identity,
            AccessAction.READ_VERSIONS,
            request,
            project_id=project_id,
        )
        rows = await conn.fetch(
            """
            SELECT rev, content_md5, changed_by, changed_at, purged_at, purged_by
              FROM project_version
             WHERE project_id = $1 AND incarnation = $2
             ORDER BY rev DESC
            """,
            project_id,
            incarnation,
        )
    return [
        {
            "rev": r["rev"],
            "md5": r["content_md5"],
            "by": r["changed_by"],
            "at": r["changed_at"].isoformat(),
            "purged": r["purged_at"] is not None,
            **(
                {
                    "purgedAt": r["purged_at"].isoformat(),
                    "purgedBy": r["purged_by"],
                }
                if r["purged_at"] is not None
                else {}
            ),
        }
        for r in rows
    ]


@router.get("/projects/{project_id}/versions/{rev}", tags=["versions"])
async def read_version(
    request: Request,
    project_id: str = ProjectId,
    rev: int = 0,
    db: Database = Depends(get_db),
    settings: Settings = Depends(get_settings),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
) -> dict[str, Any]:
    """One revision, exactly as it was stored, with its fingerprint.

    A purged revision returns an empty ``doc`` and ``purged: true``. Its
    ``md5`` is the fingerprint of the ORIGINAL content, which is what makes the
    tombstone evidence rather than a gap.
    """
    async with db.acquire() as conn, conn.transaction():
        gate = await _version_gate(conn, project_id)
        if gate is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "No such project")
        doc, incarnation = gate
        if require(
            doc,
            identity.id,
            Level.READ,
            enforced=settings.require_identity,
            project_id=project_id,
            emergency=identity.emergency,
        ):
            await emergency.record(
                conn, identity, project_id, "read this project's history", Use.READ
            )
        row = await conn.fetchrow(
            """
            SELECT rev, doc, content_md5, changed_by, changed_at, purged_at, purged_by
              FROM project_version
             WHERE project_id = $1 AND incarnation = $2 AND rev = $3
            """,
            project_id,
            incarnation,
            rev,
        )
        if row is None:
            raise HTTPException(
                status.HTTP_404_NOT_FOUND, f"No revision {rev} of {project_id!r}."
            )
        # Only a revision that exists and is returned is a read of it.
        await record_access(
            conn,
            identity,
            AccessAction.READ_VERSION,
            request,
            project_id=project_id,
            revision=row["rev"],
        )
    out: dict[str, Any] = {
        "rev": row["rev"],
        "md5": row["content_md5"],
        "by": row["changed_by"],
        "at": row["changed_at"].isoformat(),
        "doc": row["doc"],
        "purged": row["purged_at"] is not None,
    }
    if row["purged_at"] is not None:
        out["purgedAt"] = row["purged_at"].isoformat()
        out["purgedBy"] = row["purged_by"]
    return out


@router.delete(
    "/projects/{project_id}/versions",
    status_code=status.HTTP_204_NO_CONTENT,
    tags=["versions"],
)
async def purge_versions(
    project_id: str = ProjectId,
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
    settings: Settings = Depends(get_settings),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
) -> Response:
    """Destroy the stored content of every retained revision. Owner only.

    This is the disposal path. Snapshots are otherwise append-only and survive
    the project's deletion, which is right for an audit trail and wrong as an
    absolute: data entered in error -- a patient identifier pasted into an
    evidence field -- has to be removable, and before this it was not
    removable through the application at all.

    What survives is deliberate. Each row keeps its revision number, its
    author, its timestamp and its ORIGINAL ``content_md5``; only ``doc`` is
    emptied, and ``purged_at``/``purged_by`` record who did it. A row that
    vanished would be indistinguishable from a snapshot never taken. A trigger
    in 003_version_access.sql permits exactly this transition and nothing else.

    It also redacts the project's AUDIT LOG, in the same transaction. The client
    writes each entry's prose with the values in it ("Changed evidence: “old” ->
    “new”") as well as ``change.from`` and ``change.to``, and may add any other
    field it likes, so emptying the snapshots alone left the same identifier
    readable in a second table (#36). The redaction is a whitelist defined once, in
    SQL (``project_log_redacted``), and a trigger permits an UPDATE only if it
    produces exactly that. The purge is then recorded in the log by the server.

    Works on a deleted project, whose access list comes from its last snapshot
    -- otherwise the one record most likely to need purging would be the one
    record nobody could purge. (A deleted project's log is already gone with it.)
    """
    async with db.acquire() as conn, conn.transaction():
        # Serialize with a concurrent patch or delete of the live project, if any.
        live = await conn.fetchval(
            "SELECT id FROM projects WHERE id = $1 FOR UPDATE", project_id
        )
        gate = await _version_gate(conn, project_id)
        if gate is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, "No such project")
        doc, incarnation = gate
        if require(
            doc,
            identity.id,
            Level.OWN,
            enforced=settings.require_identity,
            project_id=project_id,
            emergency=identity.emergency,
        ):
            await emergency.record(
                conn,
                identity,
                project_id,
                "destroy this project's history",
                Use.WRITE,
            )
        # One timestamp for the whole purge, so the rows it touches, its log entry
        # and its security event all name the same moment, and a restore can find
        # and re-apply it (scripts/purge_ledger.py, #116).
        now = datetime.now(UTC)
        purged, through_rev = await conn.fetchrow(
            """
            WITH redacted AS (
                UPDATE project_version
                   SET doc = '{}'::jsonb, purged_at = $4, purged_by = $3
                 WHERE project_id = $1
                   AND incarnation = $2
                   AND purged_at IS NULL
             RETURNING rev
            )
            SELECT count(*), max(rev) FROM redacted
            """,
            project_id,
            incarnation,
            identity.id,
            now,
        )
        entries, through_seq = 0, None
        if live is not None:
            entries, through_seq = await conn.fetchrow(
                """
                WITH redacted AS (
                    UPDATE project_log
                       SET entry = project_log_redacted(entry),
                           purged_at = $3,
                           purged_by = $2
                     WHERE project_id = $1
                       AND purged_at IS NULL
                       AND NOT is_system
                 RETURNING seq
                )
                SELECT count(*), max(seq) FROM redacted
                """,
                project_id,
                identity.id,
                now,
            )
            if purged or entries:
                # The server records that it happened. is_system is a column the
                # client cannot set, so this entry can be neither forged nor redacted.
                plural = "entry" if entries == 1 else "entries"
                await conn.execute(
                    """
                    INSERT INTO project_log (project_id, at, by_id, entry, is_system)
                    VALUES ($1, $2, $3, $4, true)
                    """,
                    project_id,
                    now,
                    identity.id,
                    {
                        "text": (
                            f"Purged: the content of {purged or 0} revision(s) and "
                            f"{entries} audit-log {plural} was destroyed."
                        ),
                        "at": now.isoformat(timespec="milliseconds"),
                        "by": identity.id,
                    },
                )
                await broker.publish(
                    Event(
                        LOG_APPENDED,
                        project_id,
                        audience=_audience(doc, settings),
                    ),
                    conn,
                )
    emit(
        SecurityEvent.VERSIONS_PURGED,
        f"version history of {project_id} purged by {identity.id} "
        f"({purged or 0} revision(s), {entries or 0} log entries)",
        actor=identity.id,
        project=project_id,
        revisions=purged or 0,
        log_entries=entries or 0,
        # Enough to re-apply this purge to a database restored from an older dump,
        # from the security log alone, when the live database is gone (#116).
        incarnation=str(incarnation),
        purged_at=now.isoformat(),
        through_rev=through_rev,
        through_seq=through_seq,
    )
    return Response(status_code=status.HTTP_204_NO_CONTENT)


