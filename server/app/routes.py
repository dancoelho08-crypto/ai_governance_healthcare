@router.get("/events", tags=["events"])
async def events(
    request: Request,
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
    settings: Settings = Depends(get_settings),
    identity: Identity = Depends(get_identity),
) -> StreamingResponse:
    """One ``text/event-stream`` event per change, for as long as you hold it.

    Events carry an id, never a document, so the stream stays well under
    ``NOTIFY``'s 8000-byte payload cap no matter how large a project grows. The
    client refetches what changed.

    **Filtered per subscriber.** A stream only carries changes to projects its
    holder can read. Without that, every authenticated user learned the id and
    the change cadence of every project in the portfolio, including the ones
    ``GET /api/projects`` correctly filtered out of their view.

    The comment heartbeat matters more than it looks: Cloud Run, an ALB and
    Azure Front Door all close an idle connection, and an SSE stream with
    nothing to say is indistinguishable from a dead one until a byte moves.
    """

    # Registered BEFORE the StreamingResponse is built. FastAPI constructs the
    # response eagerly and runs the generator afterwards, so refusing inside
    # the generator would mean sending 200 and then an error body.
    # Who attached is part of the read trail: the stream delivers change
    # notifications (#33). A stream that cannot be recorded is not opened.
    async with db.acquire() as conn:
        await record_access(conn, identity, AccessAction.STREAM_ATTACH, request)
    try:
        subscriber = broker.attach(identity.id)
    except TooManyStreams as exc:
        emit(
            SecurityEvent.STREAM_REFUSED,
            f"refused an event stream: {exc}",
            actor=identity.id,
        )
        raise HTTPException(
            status.HTTP_429_TOO_MANY_REQUESTS,
            "Too many open event streams for this user. Close some tabs.",
        ) from exc

    async def stream() -> AsyncIterator[str]:
        started = time.monotonic()
        lifetime = settings.sse_max_lifetime_seconds
        try:
            # Tell EventSource how long to wait before reconnecting, and send
            # one frame immediately so proxies that buffer until first byte
            # release the response headers.
            yield "retry: 3000\n\n"
            yield Event("hello", None, _now_iso()).sse()
            while True:
                if await request.is_disconnected():
                    return
                # The stream authenticated once, when it attached, so it would
                # keep delivering after the account behind it was disabled (#49).
                # The API cannot ask the identity provider whether the session is
                # still good; it can end the stream, and the browser's reconnect
                # goes back through the front door and is authenticated again.
                remaining = (
                    lifetime - (time.monotonic() - started) if lifetime else None
                )
                if remaining is not None and remaining <= 0:
                    log.info("closing an event stream after %.0fs", lifetime)
                    return
                # Wake for whichever comes first, the heartbeat or the end of the
                # stream's life. Waiting a whole heartbeat would let it live that
                # much longer than the limit says.
                wait = settings.sse_keepalive_seconds
                if remaining is not None:
                    wait = min(wait, remaining)
                try:
                    event = await asyncio.wait_for(subscriber.queue.get(), timeout=wait)
                except TimeoutError:
                    if remaining is None or time.monotonic() - started < lifetime:
                        yield ": ping\n\n"
                    continue
                yield event.sse()
        finally:
            broker.detach(subscriber)

    return StreamingResponse(
        stream(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-store, no-transform",
            "Connection": "keep-alive",
            # nginx and anything derived from it buffer proxied responses by
            # default, which turns a live stream into a long silence.
            "X-Accel-Buffering": "no",
        },
    )
