@router.get("/health", response_model=HealthOut, tags=["meta"])
async def health(
    response: Response,
    request: Request,
    settings: Settings = Depends(get_settings),
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
) -> HealthOut:
    """Liveness and readiness. **Deliberately unauthenticated.**

    Every platform in ``docs/deploy.md`` health-checks this from inside the
    load balancer, where no identity header exists yet. It returns nothing
    about any project, any user, or the database's address.

    The database check is cached for a couple of seconds. Being both
    unauthenticated and exempt from the rate limiter, an uncached one let
    anyone who could reach the port pull a connection from a pool of ten as
    fast as they liked. See :meth:`Database.ping_cached`.

    The status code follows the database. Every probe this stack is deployed
    behind (docker's HEALTHCHECK, the ALB target group, Cloud Run, Container
    Apps) reads the code and ignores the body, so a 200 with ``"database":
    "down"`` kept a replica with no database in rotation and showed it as
    healthy (#46). A 503 takes it out of rotation, and the dashboard's boot
    probe reads it as a server error and says so rather than opening a
    workspace that fails on first use.
    """
    database_up = await db.ping_cached()
    if not database_up:
        response.status_code = status.HTTP_503_SERVICE_UNAVAILABLE
    return HealthOut(
        status=HealthStatus.OK if database_up else HealthStatus.UNAVAILABLE,
        events=EventDelivery.LOCAL_ONLY if broker.local_only else EventDelivery.LIVE,
        version=settings.version,
        database="up" if database_up else "down",
        db_role=request.app.state.db_role,
        idle_lock_minutes=settings.idle_lock_minutes,
        sign_out_url=settings.sign_out_url,
        auth_mode=settings.auth_mode,
        retirement_rules=(await db.retirement_rules_cached()) if database_up else None,
    )


@router.get("/principals", response_model=list[PrincipalOut], tags=["meta"])
async def principals(
    ids: str = Query(
        min_length=1,
        description=f"Comma-separated identity ids, at most {MAX_LOOKUP}.",
    ),
    db: Database = Depends(get_db),
    identity: Identity = Depends(get_identity),
    settings: Settings = Depends(get_settings),
) -> list[PrincipalOut]:
    """Names and emails for identity ids, for the ids the caller may learn.

    An access list, a sign-off and the log hold ids, and an id means nothing to a
    reviewer. This answers for the caller themself and for anyone named on a
    project the caller can read. It does NOT answer for anyone else, however the id
    was obtained, because the table behind it is a staff directory. An id it will
    not or cannot resolve is simply omitted; that is not an error.
    """
    wanted = list(dict.fromkeys(i.strip() for i in ids.split(",") if i.strip()))
    if not wanted:
        raise HTTPException(422, "ids is empty")
    if len(wanted) > MAX_LOOKUP:
        raise HTTPException(422, f"at most {MAX_LOOKUP} ids per request")
    if any(len(i) > MAX_ID_LENGTH for i in wanted):
        raise HTTPException(422, "an id is implausibly long")
    async with db.acquire() as conn:
        rows = await resolve_principals(
            conn, identity.id, wanted, enforced=settings.require_identity
        )
    return [PrincipalOut(id=r["id"], name=r["name"], email=r["email"]) for r in rows]


