@router.get("/projects", response_model=list[ProjectOut], tags=["projects"])
async def list_projects(
    request: Request,
    db: Database = Depends(get_db),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
    settings: Settings = Depends(get_settings),
) -> list[ProjectOut]:
    """Every project, as ``{id, ...document}``.

    There is no pagination and no per-user filter, because the app's dashboard
    is the whole portfolio and ``subscribeAll`` means all. A governance
    portfolio is tens of projects, not millions.
    """
    enforced = settings.require_identity
    # One transaction with its record (#33): there is no list without a row saying
    # who was given which projects, and a list that cannot be recorded is not served.
    async with db.acquire() as conn, conn.transaction():
        visible = await readable_rows(
            conn, identity.id, enforced=enforced, emergency=identity.emergency
        )
        await record_access(
            conn,
            identity,
            AccessAction.LIST,
            request,
            detail={
                "count": len(visible),
                "projects": [row["id"] for row in visible],
            },
        )
    if identity.emergency:
        # The projects this list shows only because of emergency access, counted
        # against what the project's own access lists would have shown.
        ordinary = sum(
            1
            for row in visible
            if can_read(row["doc"] or {}, identity.id, enforced=enforced)
        )
        emergency.note_listing(identity, len(visible) - ordinary)
    return [ProjectOut.from_row(row["id"], row["doc"] or {}) for row in visible]


def _listed_ids(value: Any) -> list[str]:
    """A client-supplied access list as unique strings, order kept."""
    if not isinstance(value, list):
        return []
    return list(dict.fromkeys(str(v) for v in value))


async def _check_stamp(conn: Any, document: dict[str, Any]) -> None:
    """422 unless the document's ``meta.framework`` is exactly the active primary's
    stamp. A writer who could stamp any id could keep a record from ever coming due
    for disposal (R-66, D-76)."""
    problem = stamp_problem(document, await write_primary(conn))
    if problem:
        raise HTTPException(422, problem)


async def _check_new_record(conn: Any, document: dict[str, Any]) -> None:
    """A new record's stamp. One it sets must be exactly the active primary's. One it
    leaves out makes it CHAI's (the reading every record written before stamps had),
    which is right only while CHAI is the primary: under another primary, leaving
    the stamp out would let a writer choose CHAI's rules over the primary's, so the
    create is refused (R-66)."""
    if sets_stamp(document):
        await _check_stamp(conn, document)
        return
    primary = await write_primary(conn)
    if primary != UNSTAMPED_FRAMEWORK:
        raise HTTPException(
            422,
            f'a new record must carry meta.framework {{"id": "{primary}"}}: the '
            "primary framework of the build this server retires by (R-66). A record "
            f"without one is read as {UNSTAMPED_FRAMEWORK}'s, and would retire by "
            "its rules instead.",
        )


async def _check_framework_kept(
    conn: Any, before: dict[str, Any], document: dict[str, Any], patch: Any
) -> None:
    """422 if a patch would change the framework an existing record follows, or set
    its stamp to anything but exactly ``{"id": <that framework>}``.

    A record's framework decides which decisions retire it, and so when it can be
    disposed of; no acknowledgment lists a record that a write moves (R-66). So the
    check is against the record's own framework before the patch, never against the
    active primary: a pre-switch CHAI record stamped with the new primary would stop
    coming due, and an acme record unstamped after a rollback to CHAI would start
    following CHAI's rules. Both sides are read by 010's ``record_framework()``, the
    function retention reads them with, so an absent or blank stamp is CHAI's here
    exactly as it is there."""
    was, now = await stored_frameworks(conn, before, document)
    if was != now:
        raise HTTPException(
            422,
            f"a patch cannot change a record's framework: this record follows "
            f"{was!r}'s retirement rules and the patch would make it {now!r}'s. Its "
            "framework decides which decisions retire it, and so when it can be "
            "disposed of (R-66).",
        )
    if sets_stamp(patch) and document[META_KEY][STAMP_KEY] != {STAMP_ID_KEY: was}:
        raise HTTPException(
            422,
            f'meta.framework, when a patch sets it, must be exactly {{"id": "{was}"}}, '
            "the record's own framework: a patch cannot change a record's framework, "
            "which decides which decisions retire it (R-66).",
        )


@router.post(
    "/projects/{project_id}",
    response_model=ProjectOut,
    status_code=status.HTTP_201_CREATED,
    tags=["projects"],
)
async def create_project(
    body: ProjectCreate,
    project_id: str = ProjectId,
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
    identity: Identity = Depends(get_identity),
    settings: Settings = Depends(get_settings),
) -> ProjectOut:
    """Create a project. 409 if the id is taken.

    ``INSERT ... ON CONFLICT DO NOTHING RETURNING id`` rather than
    "check, then insert": the check-then-insert version has a window in which
    two callers both see no row and the second gets a constraint error instead
    of a clean 409.
    """
    # Sign-offs are attributed to whoever is calling, never to a name the client
    # supplied (#31). Applies to a project created already carrying them too.
    doc = attribute_signoffs(
        dict(body.root),
        None,
        identity.id,
        _now_iso(),
        enforced=settings.require_identity,
    )
    access = doc.get("access") if isinstance(doc.get("access"), dict) else {}
    # Whoever creates a project owns it, whatever the body says. Two things used
    # to be possible when the client's `owners` was kept verbatim (#44): naming
    # only a colleague, which attributes a record to someone who never made it
    # and leaves its creator with no access; and mistyping an address, which
    # orphans the record at birth. The creator is always listed, first, and any
    # other owner the client named is kept, so "create and share" still works.
    # (A project with no owner at all would be "unclaimed", i.e. unrestricted.)
    if settings.require_identity and identity.id:
        named = _listed_ids(access.get("owners"))
        doc["access"] = {
            "owners": [identity.id, *(o for o in named if o != identity.id)],
            "writers": _listed_ids(access.get("writers")),
            "readers": _listed_ids(access.get("readers")),
        }
    async with db.acquire() as conn, conn.transaction():
        await _check_new_record(conn, doc)
        row = await conn.fetchrow(
            """
                INSERT INTO projects (id, doc, created_by, updated_by)
                VALUES ($1, $2, $3, $3)
                ON CONFLICT (id) DO NOTHING
                RETURNING id, incarnation
                """,
            project_id,
            doc,
            identity.id,
        )
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=f"Project {project_id!r} already exists.",
            )
        await _snapshot(conn, project_id, row["incarnation"], 1, doc, identity.id)
        await broker.publish(
            Event(PROJECT_CREATED, project_id, audience=_audience(doc, settings)),
            conn,
        )
    emit(
        SecurityEvent.PROJECT_CREATED,
        f"project {project_id} created by {identity.id}",
        level=logging.INFO,
        actor=identity.id,
        project=project_id,
    )
    return ProjectOut.from_row(project_id, doc)


@router.patch("/projects/{project_id}", response_model=ProjectOut, tags=["projects"])
async def patch_project(
    body: ProjectPatch,
    project_id: str = ProjectId,
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
    settings: Settings = Depends(get_settings),
) -> ProjectOut:
    """Deep-merge the body into the stored document.

    **Atomicity.** The merge is a read-modify-write in Python, held inside a
    transaction by ``SELECT ... FOR UPDATE``. The row lock is what makes two
    concurrent PATCHes to different fields safe: the second one blocks at the
    ``SELECT`` until the first commits, then reads the *committed* document and
    merges onto it. Neither write is lost.

    The alternative -- a recursive ``jsonb`` merge in PL/pgSQL -- would also be
    atomic, and was rejected for one reason: it would be a *second*
    implementation of a merge rule whose exact semantics (arrays replace, null
    replaces, type change replaces) the browser already defines in
    ``app/js/00-core/00-util.js``. Two implementations drift; one does not. See
    ``app/merge.py``.

    Note that PostgreSQL's ``||`` operator is not an option at all: it merges
    only the top level, so ``{"items": {"s4-2": {...}}}`` would discard every
    other key under ``items``.
    """
    patch = body.root
    async with db.acquire() as conn, conn.transaction():
        row = await conn.fetchrow(
            "SELECT doc, incarnation FROM projects WHERE id = $1 FOR UPDATE",
            project_id,
        )
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"No project {project_id!r}.",
            )
        before = row["doc"] or {}
        enforced = settings.require_identity
        used_emergency = require(
            before,
            identity.id,
            Level.WRITE,
            enforced=enforced,
            project_id=project_id,
            emergency=identity.emergency,
        )
        guard_access_change(
            before,
            patch,
            identity.id,
            enforced=enforced,
            project_id=project_id,
            emergency=identity.emergency,
        )
        guard_owner_only_fields(
            before,
            patch,
            identity.id,
            enforced=enforced,
            project_id=project_id,
            emergency=identity.emergency,
        )
        if used_emergency:
            await emergency.record(
                conn, identity, project_id, "change this project", Use.WRITE
            )
        # Who signed, and when, is the server's to say (#31). After the guards,
        # so an unauthorized caller is refused before anything is rewritten.
        patch = attribute_signoffs(
            patch, before, identity.id, _now_iso(), enforced=enforced
        )
        try:
            document = merged(before, patch)
        except TooDeep as exc:
            raise HTTPException(status.HTTP_400_BAD_REQUEST, str(exc)) from exc
        # The record's framework decides which rules retire it (R-66): no patch
        # changes it. Checked against the record, not the active primary, so this
        # needs no lock against a sync.
        await _check_framework_kept(conn, before, document, patch)
        rev = await conn.fetchval(
            """
                UPDATE projects
                   SET doc = $2, rev = rev + 1, updated_at = now(), updated_by = $3
                 WHERE id = $1
             RETURNING rev
                """,
            project_id,
            document,
            identity.id,
        )
        await _snapshot(
            conn, project_id, row["incarnation"], rev, document, identity.id
        )
        await broker.publish(
            Event(
                PROJECT_UPDATED,
                project_id,
                audience=_audience(document, settings),
            ),
            conn,
        )
    return ProjectOut.from_row(project_id, document)


@router.delete(
    "/projects/{project_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    tags=["projects"],
)
async def delete_project(
    project_id: str = ProjectId,
    db: Database = Depends(get_db),
    broker: EventBroker = Depends(get_broker),
    identity: Identity = Depends(get_identity),
    emergency: EmergencyAudit = Depends(get_emergency),
    settings: Settings = Depends(get_settings),
) -> Response:
    """Delete the live project and its audit log. It does NOT erase the history.

    The log goes with it by ``ON DELETE CASCADE``. That is the only way log
    rows are ever removed -- there is no endpoint that deletes an entry.

    Every revision's full document is KEPT in ``project_version``, on purpose: an
    audit trail that vanishes with its subject is not one. So deleting is not
    erasure. ``DELETE .../versions`` is the second, separate step that destroys
    the history (#36).

    What deletion leaves behind is written here, in the same transaction, to
    ``project_deletion``: who deleted it, when, and what its last revision hashed
    to. Before this the only record was a line on container stdout.
    """
    async with db.acquire() as conn, conn.transaction():
        current = await conn.fetchrow(
            "SELECT doc FROM projects WHERE id = $1 FOR UPDATE", project_id
        )
        if current is not None:
            if require(
                current["doc"] or {},
                identity.id,
                Level.OWN,
                enforced=settings.require_identity,
                project_id=project_id,
                emergency=identity.emergency,
            ):
                await emergency.record(
                    conn, identity, project_id, "delete this project", Use.DELETE
                )
            # The tombstone is written AFTER the access check and BEFORE the
            # delete, from the same row lock, so a refused or failed delete
            # leaves nothing behind and a successful one cannot lose it.
            await conn.execute(
                """
                INSERT INTO project_deletion
                       (project_id, incarnation, deleted_by, last_rev, last_md5)
                SELECT p.id, p.incarnation, $2, p.rev, v.content_md5
                  FROM projects p
                  LEFT JOIN project_version v
                         ON v.project_id = p.id
                        AND v.incarnation = p.incarnation
                        AND v.rev = p.rev
                 WHERE p.id = $1
                """,
                project_id,
                identity.id,
            )
        row = await conn.fetchrow(
            "DELETE FROM projects WHERE id = $1 RETURNING id", project_id
        )
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"No project {project_id!r}.",
            )
        # The audience comes from the document as it was BEFORE the delete:
        # afterwards there is no access list to read, and defaulting to
        # "everyone" at that point would announce the deletion of a record
        # most subscribers were never allowed to know about.
        await broker.publish(
            Event(
                PROJECT_DELETED,
                project_id,
                audience=_audience(current["doc"] or {}, settings)
                if current is not None
                else None,
            ),
            conn,
        )
    emit(
        SecurityEvent.PROJECT_DELETED,
        f"project {project_id} deleted by {identity.id}",
        level=logging.INFO,
        actor=identity.id,
        project=project_id,
    )
    return Response(status_code=status.HTTP_204_NO_CONTENT)


# --- version history --------------------------------------------------------

# Excluded from the fingerprint. Must match CANON_SKIP in
# app/js/00-core/12-hash.js, or the browser and the server will disagree about
# what the same record hashes to -- which is worse than having no hash, because
# it looks like evidence of a change that did not happen.
# tests/test_fingerprint_skip.py fails if they differ (#177).
_HASH_SKIP = frozenset(
    {"updatedAt", "updatedBy", "cardUpdatedAt", "_state", "contentHash", "generated"}
)


def _canonical(value: Any, _depth: int = 0) -> Any:
    """Deterministic shape: keys sorted at every depth, volatile keys dropped.

    Bounded for the same reason deep_merge is: this runs on every write, and
    a RecursionError here would fail the snapshot of a document the caller
    had already been told was accepted.
    """
    if _depth > MERGE_MAX_DEPTH:
        raise TooDeep(f"document nests deeper than {MERGE_MAX_DEPTH} levels")
    if isinstance(value, dict):
        return {
            k: _canonical(value[k], _depth + 1)
            for k in sorted(value, key=_utf16)
            if k not in _HASH_SKIP
        }
    if isinstance(value, list):
        return [_canonical(v, _depth + 1) for v in value]
    return value


def _utf16(key: str) -> bytes:
    """The order the browser sorts keys in: by UTF-16 code unit, not code point.

    They differ when one key has a character from U+E000 to U+FFFF where another
    has one above U+FFFF (an emoji): Python put the emoji last, the browser first,
    and the same record hashed to two values (#177).
    """
    return key.encode("utf-16-be", "surrogatepass")


def content_md5(doc: dict[str, Any]) -> str:
    """The same fingerprint the browser computes, over the same canonical form.

    ``doc`` is the record as stored, its id included (``_snapshot`` adds it). The
    dashboard hashes the stored record too, not the copy it fills in for display
    (an older record lacks fields it fills), so a revision's fingerprint is the
    one the setup page and the exports show for the same record (#177).

    MD5 because that is what the record is labeled with; it answers "is this
    the same version?" and nothing stronger. It is not a tamper seal, and
    anything that presents it as one is wrong -- see the note in the app's
    changelog view.
    """
    # Not sort_keys: _canonical has put the keys in the browser's order already,
    # and sorting again would put them back in Python's.
    canon = _json.dumps(_canonical(doc), separators=(",", ":"), ensure_ascii=False)
    # A lone surrogate is written as its \u escape, lowercase, as JSON.stringify
    # writes it; UTF-8 cannot encode it, and every other character encodes, so
    # backslashreplace touches nothing else (#177).
    return hashlib.md5(canon.encode("utf-8", "backslashreplace")).hexdigest()


async def _snapshot(
    conn: Any,
    project_id: str,
    incarnation: Any,
    rev: int,
    doc: dict[str, Any],
    by: str | None,
) -> None:
    """Record one immutable version. Caller supplies the open transaction.

    The access list is copied onto the row. That is what keeps history as
    restricted as the record was: a deleted project has no live document to
    check against, and without this its snapshots were readable by anyone who
    could reach the API. See ``003_version_access.sql``.
    """
    access = doc.get("access") if isinstance(doc.get("access"), dict) else {}
    # No ON CONFLICT. A conflict here means two snapshots claim the same
    # (project, incarnation, revision), which cannot happen while the caller
    # holds the row lock -- so if it does, something is wrong and the write
    # should fail loudly. The previous DO NOTHING silently dropped the rev 1 of
    # a project that reused a deleted id, leaving a history with a missing
    # first revision and no indication of it.
    await conn.execute(
        """
        INSERT INTO project_version
               (project_id, incarnation, rev, doc, content_md5, changed_by, access)
        VALUES ($1, $2, $3, $4, $5, $6, $7)
        """,
        project_id,
        incarnation,
        rev,
        doc,
        content_md5({**doc, "id": project_id}),
        by,
        access,
    )


async def _version_gate(
    conn: Any, project_id: str
) -> tuple[dict[str, Any], Any] | None:
    """Which history to read, and the access list that governs reading it.

    Returns ``(doc_for_access_check, incarnation)``, or ``None`` when there is
    no history at all -- which the caller turns into a 404.

    The incarnation matters as much as the access list. Project ids are
    caller-chosen and snapshots outlive their project, so one id can have two
    unrelated histories: the deleted project's, and the one someone created
    afterwards reusing the id. Reads are scoped to the LIVE project's
    incarnation when there is one, and to the most recent incarnation
    otherwise, so a reused id never shows two records merged into one.

    Access comes from the live project where there is one, and otherwise from
    the access list recorded on that incarnation's most recent snapshot -- so
    deleting a project does not turn its history into a public record.
    """
    live = await conn.fetchrow(
        "SELECT doc, incarnation FROM projects WHERE id = $1", project_id
    )
    if live is not None:
        return (live["doc"] or {}), live["incarnation"]
    row = await conn.fetchrow(
        """
        SELECT access, incarnation FROM project_version
         WHERE project_id = $1
         ORDER BY changed_at DESC, rev DESC
         LIMIT 1
        """,
        project_id,
    )
    if row is None:
        return None
    return {"access": row["access"] or {}}, row["incarnation"]


